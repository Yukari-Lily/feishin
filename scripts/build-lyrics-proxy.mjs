/**
 * Bundles the vendored lyrics proxy into the entry point each platform looks
 * for:
 *
 *   lyrics-proxy/entries/vercel.js   -> api/lyrics/[...path].mjs
 *   lyrics-proxy/entries/edgeone.js  -> functions/api/lyrics/[[default]].js
 *
 * Both outputs are committed, so neither Vercel nor EdgeOne Pages needs a
 * build step; this script only has to be re-run after editing
 * lyrics-proxy/src/:
 *
 *   node scripts/build-lyrics-proxy.mjs
 *
 * esbuild is deliberately not a declared dependency of this repo (that would
 * touch package.json and pnpm-lock.yaml, the two files most likely to conflict
 * when merging upstream), so it is resolved from the installed tree - vite
 * always brings it in. Regenerating by hand with npx works too:
 *
 *   npx --yes esbuild@0.25.12 lyrics-proxy/entries/vercel.js \
 *       --bundle --format=esm --target=es2022 --outfile="api/lyrics/[...path].mjs"
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const HEADER = '/* Generated by scripts/build-lyrics-proxy.mjs - do not edit. */\n';

const TARGETS = [
    {
        entry: 'lyrics-proxy/entries/vercel.js',
        outfile: 'api/lyrics/[...path].mjs',
        platform: 'node',
    },
    {
        entry: 'lyrics-proxy/entries/edgeone.js',
        outfile: 'functions/api/lyrics/[[default]].js',
        platform: 'neutral',
    },
];

// Candidate module specifiers, most likely first.
const esbuildCandidates = ['esbuild'];
const pnpmDir = path.join(root, 'node_modules', '.pnpm');

if (fs.existsSync(pnpmDir)) {
    for (const entry of fs.readdirSync(pnpmDir)) {
        if (entry.startsWith('esbuild@')) {
            esbuildCandidates.push(
                path.join(pnpmDir, entry, 'node_modules', 'esbuild', 'lib', 'main.js'),
            );
        }
    }
}

esbuildCandidates.push(path.join(root, 'node_modules', 'esbuild', 'lib', 'main.js'));

let build;

for (const candidate of esbuildCandidates) {
    try {
        const module = await import(candidate);
        if (typeof module.build === 'function') {
            build = module.build;
            break;
        }
    } catch {
        // try the next candidate
    }
}

if (!build) {
    throw new Error(
        'esbuild could not be resolved. Run `pnpm add -D esbuild` once, or regenerate with ' +
            '`npx --yes esbuild@0.25.12 lyrics-proxy/entries/vercel.js --bundle --format=esm ' +
            '--target=es2022 --outfile=api/lyrics/[...path].mjs` (same for the edgeone entry).',
    );
}

for (const target of TARGETS) {
    await build({
        banner: { js: HEADER },
        bundle: true,
        entryPoints: [path.join(root, target.entry)],
        format: 'esm',
        logLevel: 'info',
        outfile: path.join(root, target.outfile),
        platform: target.platform,
        target: 'es2022',
    });
}
